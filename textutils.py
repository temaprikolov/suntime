#!/usr/bin/env python3
"""
Утилиты для безопасной вставки пользовательского текста в сообщения
с parse_mode="HTML".

БАГ, который это чинит: Telegram отправляет сообщение с HTML-разметкой,
парся её на своей стороне. Если в тексте, который мы туда подставляем,
встречается "<", ">" или одиночный "&" (а это может быть что угодно —
имя пользователя в Telegram (first_name), никнейм в профиле, контакт
для связи, текст объявления на "Рынке" и т.д. — все эти поля пользователь
вводит свободно), Telegram отвечает ошибкой "can't parse entities" и
сообщение НЕ отправляется вообще. Из-за этого, например, раньше могла
полностью и без возможности исправления сломаться карточка профиля
у конкретного пользователя (если в его нике или имени Telegram оказывался
символ "<"), просмотр конкретного заказа в админке (если в контакте
покупателя был "<" или "&") и т.п.

Используйте esc() при вставке ЛЮБОГО пользовательского текста
(first_name, nickname, contact, title, description и т.д.) в строку,
которая отправляется с parse_mode="HTML".
"""
import html as _html


def esc(value) -> str:
    """Экранирует текст для безопасной вставки в HTML-сообщение Telegram.
    None превращается в пустую строку, всё остальное — приводится к str()."""
    if value is None:
        return ""
    return _html.escape(str(value), quote=False)
